#!/bin/sh
# Regenerates ../look_shaders.h from the HLSL here, with Wine's d3dcompiler_47. Plain `make` doesn't need this.
# Keeps its Wine prefix and compiler in $HLSL_TMP (default: a temp folder).
set -e
cd "$(dirname "$0")"
T=${HLSL_TMP:-${TMPDIR:-/tmp}/taz-hlsl}
mkdir -p "$T"
i686-w64-mingw32-gcc -O1 -s -o "$T/hlslc.exe" hlslc.c
cp scene.hlsl post.hlsl "$T/"
out=$T/look_shaders.h
echo "// Generated by src/d3d8/shaders/build.sh from scene.hlsl and post.hlsl. Do not edit." > "$out"
c() { # file entry profile name [defines]
    f=$1 e=$2 p=$3 n=$4; shift 4
    (cd "$T" && WINEPREFIX="$T/prefix" WINEDEBUG=-all wine hlslc.exe "$f" "$e" "$p" "$n" "$@" 2>"$n.err" | tr -d '\r' >> look_shaders.h) || true
    grep -q "$n\[" "$out" || { cat "$T/$n.err" >&2; echo "failed: $n" >&2; exit 1; }
}
c scene.hlsl vs_world vs_3_0 vs_world
c scene.hlsl vs_world vs_3_0 vs_world_float AT_WATERLINE
c scene.hlsl vs_inst vs_3_0 vs_inst
c scene.hlsl vs_inst vs_3_0 vs_water WATER_SURFACE
c scene.hlsl vs_inst vs_3_0 vs_inst_wind WINDY
c scene.hlsl vs_inst vs_3_0 vs_grass GRASS WINDY
c scene.hlsl vs_world_depth vs_3_0 vs_world_depth
c scene.hlsl vs_inst_depth vs_3_0 vs_inst_depth
c scene.hlsl vs_inst_depth vs_3_0 vs_grass_depth GRASS WINDY
c scene.hlsl vs_sky vs_3_0 vs_sky
c scene.hlsl vs_char_depth vs_3_0 vs_char_depth
c scene.hlsl vs_prop vs_2_0 vs_prop
c scene.hlsl ps_depth ps_3_0 ps_depth
c scene.hlsl ps_world ps_3_0 ps_world
c scene.hlsl ps_world ps_3_0 ps_world_mat MATERIAL
c scene.hlsl ps_world ps_3_0 ps_world_mat2 MATERIAL MATERIAL2
c scene.hlsl ps_inst ps_3_0 ps_inst
c scene.hlsl ps_inst ps_3_0 ps_inst_tiled TILED
c scene.hlsl ps_inst ps_3_0 ps_card CUT
c scene.hlsl ps_inst ps_3_0 ps_grass CUT GRASS
c scene.hlsl ps_water ps_3_0 ps_water
c scene.hlsl ps_sky ps_3_0 ps_sky
c scene.hlsl ps_glass ps_3_0 ps_glass
c scene.hlsl ps_space ps_2_b ps_space
c scene.hlsl ps_char ps_2_b ps_char
c scene.hlsl ps_glow ps_2_0 ps_glow
c post.hlsl vs_quad vs_3_0 vs_quad
c post.hlsl ps_bright ps_3_0 ps_bright
c post.hlsl ps_down ps_3_0 ps_down
c post.hlsl ps_up ps_3_0 ps_up
c post.hlsl ps_final ps_3_0 ps_final
c post.hlsl ps_ao ps_3_0 ps_ao
c post.hlsl ps_ao_blur ps_3_0 ps_ao_blur
c post.hlsl ps_ao_up ps_3_0 ps_ao_up
cp "$out" ../look_shaders.h
wc -c ../look_shaders.h
